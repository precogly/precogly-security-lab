"""Precogly cross-tenant checks and a stable SARIF writer for Schemathesis."""

from __future__ import annotations

import atexit
import json
import os
import runpy
import threading
from pathlib import Path
from typing import Any

import requests
import schemathesis
from schemathesis.engine import Status

# Keep the image's TraceCov integration. Pointing SCHEMATHESIS_HOOKS at this file
# is required: 4.32.0 crashes if the same hook is named through config instead.
runpy.run_path("/app/hooks.py")

BASE = "http://backend:8000"
HEADERS = {"X-Forwarded-Proto": "https"}
_tokens: dict[str, str] = {}
_demo_ids: set[str] = set()
_object_reads: set[tuple[str, str]] = set()
_probed_reads: set[tuple[str, str]] = set()
_findings: dict[tuple[str, str, str], dict[str, str]] = {}
_lock = threading.Lock()
_schema_loaded = False


def login(email: str) -> str:
    response = requests.post(
        f"{BASE}/api/auth/login/",
        json={"email": email, "password": "admin123"},
        headers=HEADERS,
        timeout=30,
        allow_redirects=False,
    )
    response.raise_for_status()
    return response.json()["access"]


@schemathesis.auth(refresh_interval=600)
class AdminLogin:
    def get(self, case: Any, ctx: Any) -> str:
        return login("admin@precogly.dev")

    def set(self, case: Any, data: str, ctx: Any) -> None:
        case.headers = case.headers or {}
        case.headers["Authorization"] = f"Bearer {data}"


def _peer_headers() -> dict[str, str]:
    if "contoso" not in _tokens:
        _tokens["contoso"] = login("contoso@precogly.dev")
    return {**HEADERS, "Authorization": f"Bearer {_tokens['contoso']}"}


def _ids(value: Any) -> set[str]:
    """IDs named by a request or response, including paginated list results."""
    found: set[str] = set()
    if isinstance(value, dict):
        for key, child in value.items():
            if key == "id" and isinstance(child, str):
                found.add(child)
            found.update(_ids(child))
    elif isinstance(value, list):
        for child in value:
            found.update(_ids(child))
    return found


def _route(case: Any) -> str:
    return case.operation.path


def _record(rule: str, method: str, route: str, message: str) -> None:
    # SecObserve identifies SARIF observations by title + location. Neither may
    # contain the random IDs generated by this stack.
    with _lock:
        _findings[(rule, method.upper(), route)] = {
            "rule": rule,
            "method": method.upper(),
            "route": route,
            "message": message,
        }


@schemathesis.hook
def after_load_schema(context: Any, schema: Any) -> None:
    global _schema_loaded
    _schema_loaded = True
    for result in schema.get_all_operations():
        operation = result.ok() if hasattr(result, "ok") else None
        if (
            operation is not None
            and str(operation.method).upper() == "GET"
            and "{" in operation.path
            and not operation.path.startswith("/api/auth/")
        ):
            _object_reads.add(("GET", operation.path))


@schemathesis.check
def CrossTenant(context: Any, response: Any, case: Any) -> None:
    if not 200 <= response.status_code < 300:
        return
    method, route = case.method.upper(), _route(case)
    try:
        owner_json = response.json()
    except ValueError:
        owner_json = None

    if method == "GET" and case.path_parameters:
        _probed_reads.add((method, route))
        peer = case.call(headers=_peer_headers())
        if peer.status_code in (403, 404):
            _demo_ids.update(str(value) for value in case.path_parameters.values())
            return
        detail = f"HTTP {peer.status_code} for {method} {route}"
        raise AssertionError(f"Cross-tenant read: peer received {detail}")

    if method == "GET":
        peer = case.call(headers=_peer_headers())
        try:
            peer_json = peer.json()
        except ValueError:
            peer_json = None
        leaked = _ids(peer_json) & _demo_ids
        if leaked:
            raise AssertionError(
                f"Cross-tenant list exposed Demo-owned IDs at GET {route}"
            )
        return

    named = _ids(case.body) | {
        str(value) for value in (case.path_parameters or {}).values()
    }
    if named & _demo_ids:
        peer = case.call(headers=_peer_headers())
        if 200 <= peer.status_code < 300:
            detail = f"HTTP {peer.status_code} for {method} {route}"
            raise AssertionError(f"Cross-tenant write: peer received {detail}")
    _demo_ids.update(_ids(owner_json))


@schemathesis.hook
def after_validate(context: Any, case: Any, response: Any, results: list[Any]) -> None:
    for result in results:
        if result.status != Status.FAILURE or result.failure is None:
            continue
        rule = "cross-tenant" if result.name == "CrossTenant" else result.name
        _record(rule, case.method, _route(case), str(result.failure))


def _write_sarif() -> None:
    # A CLI/config/schema failure is not a clean scan. With no report, lab marks
    # the job failed and, critically, does not resolve the previous findings.
    if not _schema_loaded:
        return
    for method, route in sorted(_object_reads - _probed_reads):
        _record(
            "unprobed-object-read",
            method,
            route,
            "Schemathesis never received a successful owner response for "
            f"{method} {route}; the cross-tenant replay did not run.",
        )
    rules = {
        "cross-tenant": ("Cross-tenant authorization", "error"),
        "unprobed-object-read": ("Cross-tenant object read not probed", "note"),
    }
    for finding in _findings.values():
        rules.setdefault(
            finding["rule"], (finding["rule"].replace("_", " ").title(), "warning")
        )
    document = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [
            {
                "tool": {
                    "driver": {
                        "name": "Schemathesis",
                        "version": "4.32.0",
                        "rules": [
                            {
                                "id": rule,
                                "name": title,
                                "defaultConfiguration": {"level": level},
                            }
                            for rule, (title, level) in sorted(rules.items())
                        ],
                    }
                },
                "results": [
                    {
                        "ruleId": item["rule"],
                        "level": rules[item["rule"]][1],
                        "message": {"text": item["message"]},
                        "locations": [
                            {
                                "physicalLocation": {
                                    "artifactLocation": {
                                        "uri": f"{item['method']} {item['route']}"
                                    }
                                }
                            }
                        ],
                    }
                    for item in sorted(
                        _findings.values(),
                        key=lambda value: (
                            value["rule"],
                            value["method"],
                            value["route"],
                        ),
                    )
                ],
            }
        ],
    }
    out = Path(os.environ.get("OUT_DIR", "/out")) / "report.sarif"
    out.write_text(json.dumps(document, indent=2) + "\n")


atexit.register(_write_sarif)
